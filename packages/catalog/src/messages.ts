export function createCatalogTranslator(
  brand: { locale: string; messages?: Record<string, string> },
  presentation: "products" | "services" = "products",
): Translator {
  if (presentation === "products") return createTranslator(brand, catalogMessages);
  return createTranslator(brand, {
    id: { ...catalogMessages.id, ...serviceMessages.id },
    en: { ...catalogMessages.en, ...serviceMessages.en },
  });
}

/** Keep validation errors from the module's existing mutation flow localizable. */
export function localizeCatalogError(error: unknown, t: Translator): string {
  if (!(error instanceof Error)) return t("catalog.products.formError");
  const message = error.message;
  const required = message.match(/^(.+) wajib diisi\.$/);
  if (required) {
    const requiredName = required[1] ?? "";
    const labels: Record<string, string> = {
      "Nama produk": t("catalog.products.form.name"),
      "Nama layanan": t("catalog.products.form.name"),
      Deskripsi: t("catalog.products.form.description"),
      SKU: t("catalog.products.form.sku"),
      Kategori: t("catalog.products.form.category"),
    };
    return t("catalog.products.error.required", { name: labels[requiredName] ?? requiredName });
  }
  const known: Record<string, string> = {
    "Harga tidak valid.": "catalog.products.error.invalidPrice",
    "Stok harus berupa bilangan bulat positif.": "catalog.products.error.invalidStock",
    "File produk harus berupa gambar.": "catalog.products.error.invalidFile",
    "File layanan harus berupa gambar.": "catalog.products.error.invalidFile",
    "Ukuran gambar maksimal 5 MB.": "catalog.products.error.imageSize",
    "Gambar produk wajib diunggah.": "catalog.products.error.imageRequired",
    "Gambar layanan wajib diunggah.": "catalog.products.error.imageRequired",
    "Product not found": "catalog.products.error.notFound",
    "Tipe pemenuhan tidak valid.": "catalog.products.error.invalidFulfillmentType",
  };
  return known[message] ? t(known[message]) : t("catalog.products.formError");
}
